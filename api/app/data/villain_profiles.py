def _size_profile(
    *,
    small_bet: tuple[float, float] = (0.25, 0.40),
    medium_bet: tuple[float, float] = (0.45, 0.70),
    big_bet: tuple[float, float] = (0.75, 1.10),
    overbet: tuple[float, float] = (1.05, 1.35),
    small_raise: tuple[float, float] = (2.20, 2.80),
    normal_raise: tuple[float, float] = (2.80, 3.50),
    big_raise: tuple[float, float] = (4.00, 5.00),
    allow_overbet_bet: bool = True,
    allow_overbet_raise: bool = True,
    dynamic_sizing: bool = False,
    equity_size_correlation: float = 0.50,
    vulnerability_size_correlation: float = 0.35,
    bluff_size_discount: float = 0.10,
    polar_overbet_bonus: float = 0.0,
) -> SizeProfile:
    return SizeProfile(
        small_bet=NumericBand(*small_bet),
        medium_bet=NumericBand(*medium_bet),
        big_bet=NumericBand(*big_bet),
        overbet=NumericBand(*overbet),
        small_raise=NumericBand(*small_raise),
        normal_raise=NumericBand(*normal_raise),
        big_raise=NumericBand(*big_raise),
        allow_overbet_bet=allow_overbet_bet,
        allow_overbet_raise=allow_overbet_raise,
        dynamic_sizing=dynamic_sizing,
        equity_size_correlation=equity_size_correlation,
        vulnerability_size_correlation=vulnerability_size_correlation,
        bluff_size_discount=bluff_size_discount,
        polar_overbet_bonus=polar_overbet_bonus,
    )


